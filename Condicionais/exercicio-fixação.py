#  Solicite a temperatura para o usuário.
# Se tiver abaixo de 16 graus, informe ao usuário para pegar uma blusa. 
# Ao final escreva fim do programa.



# Entrada
temperatura = int(input(" Digite a temperatura: "))


# Processamento
if temperatura <= 16:
    print("Pegue a  blusa de frio")
else:
    print("Pegue um óculos de sol")
        
        
        
